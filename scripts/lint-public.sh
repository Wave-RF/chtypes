  printf 'the internal measurements directory tracks throughput over time\n' > "$tmp/legal-docsmeasurements-word.md"

  printf 'the failure only reproduced under Wave-RF/software/chtypes/wt-goblin-3\n' > "$tmp/planted-housing.md"
  printf 'the housing folder holds both repositories side by side\n' > "$tmp/legal-housing-word.md"

  # --- issue #224: CI_INFRA_PATH_PATTERN replaces the old single-file
  #     `ci/steps/` literal with a shape match, so a DIFFERENT file under the
  #     same top-level directory (the actual leak, scripts/fetch.sh citing
  #     ci/resolve-version.py) is caught too, and so is `infra/` (the former
  #     chtypes-infra repository, folded into the private one on 2026-09-10).
  #     Negative control: "ci/" is common enough as a bare substring that a
  #     word simply ending in it must NOT fire — see the header note above. ---
  printf 'the resolver lives at ci/resolve-version.py in that tree\n' > "$tmp/planted-ci-path.md"
  printf 'infra/terraform holds the module for that account\n' > "$tmp/planted-infra-path.md"
  printf 'built with github.com/golangci/misspell, same as everywhere else\n' > "$tmp/legal-golangci-word.md"

  # --- issue #224: tests/fixtures/fetch/ used to be exempt from every rule in
