"""The shared revocation-statement table (tests/fixtures/revocation-statement/
cases.json), generated by the delivery side's registry tests and read by all four
bindings: which signed revocation statements count (docs/guides/fetch-v1.md,
"Build-level revocation", rule 5), and that the first verifying revocation in a
listing wins. The statement rows call `verify_revocation`; the listing rows drive
the real candidate loop through `check_installed` against a local registry."""

