DIR = Path(__file__).resolve().parents[3] / "tests" / "fixtures" / "revocation-statement"
TABLE = DIR / "cases.json"
FIELDS = ("id", "url", "class", "summary", "superseded_by", "revoked_at")

if not TABLE.is_file():
    pytest.skip(
        f"SKIPPED: the shared revocation-statement table is not beside this checkout ({TABLE})",
        allow_module_level=True,
    )

_DOC = json.loads(TABLE.read_text(encoding="utf-8"))
_BUILD = json.loads((DIR / "build.predicate.json").read_text(encoding="utf-8"))
_KEY = bytes.fromhex((DIR / "key.pub.hex").read_text().strip())
_KEYS = (TrustedKey(keyid=hashlib.sha256(_KEY).hexdigest()[:16], public_key=_KEY),)


def _advisory(a) -> dict:  # noqa: ANN001
    return {
        "id": a.id,
        "url": a.url,
        "class": a.class_,
        "summary": a.summary,
        "superseded_by": a.superseded_by,
        "revoked_at": a.revoked_at,
    }


def _digest(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


@pytest.fixture
def prod_v2() -> Iterator[None]:
    restore = _channel.use_prod_v2_for_tests()
    reset_revocation_memo_for_tests()
    try:
        yield
    finally:
        reset_revocation_memo_for_tests()
        restore()


def test_the_table_has_rows() -> None:
    assert _DOC["cases"] and _DOC["listings"], "an empty table would check nothing"
    assert any(c["expect"] == "verifies" for c in _DOC["cases"])
    assert any(r["expect"] == "revoked" for r in _DOC["listings"])


@pytest.mark.parametrize("case", _DOC["cases"], ids=lambda c: c["name"])
def test_statement_case(case: dict) -> None:
    sub = Subject(
        manifest=_BUILD["manifest"],
        layer=_BUILD["layer"],
        predicate=_BUILD["predicate"],
        version="26.8.15.10",
        platform="linux-amd64",
        build="20260101.000000",
        request="26.8",
        dir=None,
        writable=False,
    )
    rev, reason = verify_revocation((DIR / case["bundle"]).read_bytes(), _KEYS, sub)
    if case["expect"] == "ignored":
        assert rev is None, f"{case['name']} verifies, want it refused"
        assert reason, "refused with no reason"
        return
    assert case["expect"] == "verifies"
    assert rev is not None, f"{case['name']} does not verify ({reason})"
    assert len(rev.advisories) == 1
    assert _advisory(rev.advisories[0]) == case["expect_advisory"]
    has_fix = case["expect_advisory"]["superseded_by"] != ""
    assert has_fix == ("; superseded by build " in revoked_text(sub, rev)), revoked_text(sub, rev)


class _Registry:
    """Serves one build's referrers listing in order, each referrer's manifest and
    its bundle; `served` maps a bundle file to the manifest digest it is served
    under."""

    def __init__(self, referrers: list[str]) -> None:
        objects: dict[str, bytes] = {}
        self.served: dict[str, str] = {}
        manifests = [
            {
                "mediaType": C.MEDIA_TYPE_MANIFEST,
                "digest": _digest(b"signature"),
                "size": 9,
                "artifactType": C.MEDIA_TYPE_BUNDLE,  # the listing must name a signature
            }
        ]
        for name in referrers:
            bundle = (DIR / name).read_bytes()
            layer = {
                "mediaType": C.MEDIA_TYPE_BUNDLE,
                "digest": _digest(bundle),
                "size": len(bundle),
            }
            body = json.dumps(
                {
                    "schemaVersion": 2,
                    "mediaType": C.MEDIA_TYPE_MANIFEST,
                    "artifactType": C.REVOCATION_ARTIFACT_TYPE,
                    "config": {
                        "mediaType": "application/vnd.oci.empty.v1+json",
                        "digest": _digest(b"{}"),
                        "size": 2,
                    },
                    "layers": [layer],
                }
            ).encode()
            digest = _digest(body)
            self.served[name] = digest
            objects["/manifests/" + digest] = body
            objects["/blobs/" + layer["digest"]] = bundle
            manifests.append(
                {
                    "mediaType": C.MEDIA_TYPE_MANIFEST,
                    "digest": digest,
                    "size": len(body),
                    "artifactType": C.REVOCATION_ARTIFACT_TYPE,
                }
            )
        objects["/referrers/" + _BUILD["manifest"]] = json.dumps(
            {"schemaVersion": 2, "mediaType": C.MEDIA_TYPE_INDEX, "manifests": manifests}
        ).encode()

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args) -> None:  # noqa: D102
                pass

            def do_GET(self) -> None:  # noqa: N802
                for suffix, body in objects.items():
                    if self.path.endswith(suffix):
                        self.send_response(200)
                        self.send_header("Content-Length", str(len(body)))
                        self.end_headers()
                        self.wfile.write(body)
                        return
                self.send_response(404)
                self.send_header("Content-Length", "0")
                self.end_headers()

        self._httpd = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self._httpd.daemon_threads = True
        threading.Thread(target=self._httpd.serve_forever, daemon=True).start()

    @property
    def base(self) -> str:
        host, port = self._httpd.server_address[:2]
        return f"http://{host}:{port}/chtypes/v2"

    def stop(self) -> None:
        self._httpd.shutdown()
        self._httpd.server_close()


@pytest.mark.parametrize("listing", _DOC["listings"], ids=lambda r: r["name"])
def test_listing_case(prod_v2: None, listing: dict, tmp_path: Path) -> None:
    registry = _Registry(listing["referrers"])
    try:
        manifest = _BUILD["manifest"]
        entry = resolve_cache_root(tmp_path) / "unpacked" / "sha256" / manifest.split(":")[1]
        entry.mkdir(parents=True)
        res = Resolved(
            abi_generation=2,
            platform="linux-amd64",
            request="26.8",
            version="26.8.15.10",
            channel=None,
            build="20260101.000000",
            library_path=entry / "libchtypes.so",
            dir=entry,
            digests={"manifest": manifest, "layer": _BUILD["layer"], "index": None, "bundle": None},
            predicate=_BUILD["predicate"],
            signed_by="",
            source="cache",
            already_installed=True,
        )
        opts = Options(
            bases=(registry.base,), cache_dir=tmp_path, system_dirs=(), trusted_keys=_KEYS
        )
        warnings: list[str] = []
        revoked: ArtifactRevokedError | None = None
        try:
            warnings = check_installed(res, opts)
        except ArtifactRevokedError as exc:
            revoked = exc
            warnings = list(getattr(exc, "warnings", ()))
    finally:
        registry.stop()

    ignored = [registry.served[f] for f in listing["ignored"]]
    dont_care = [registry.served[f] for f in listing.get("dont_care", [])]
    for digest in ignored:
        assert any(digest in w and "does not verify and is ignored" in w for w in warnings), (
            f"no warning names ignored referrer {digest}: {warnings}"
        )
    for w in warnings:
        assert "does not verify and is ignored" in w, f"unexpected warning {w!r}"
        assert any(d in w for d in ignored + dont_care), f"warning names no listed referrer: {w!r}"

    if listing["expect"] == "revoked":
        assert revoked is not None, "the build was allowed, want CHTYPES_ARTIFACT_REVOKED"
        rev = revoked.revocation
        assert rev is not None and rev.signed and len(rev.advisories) == 1
        assert _advisory(rev.advisories[0]) == listing["expect_advisory"]
    else:
        assert listing["expect"] == "fail-open"
        assert revoked is None, "the build was refused, want it allowed"
